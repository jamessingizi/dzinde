"""Static HTML family-history website (RootsMagic 'HTML Website' equivalent)."""
import os
import shutil
from html import escape as E

from . import model as m, rmdate
from .db import rows

CSS = """body{font:15px/1.5 Georgia,serif;max-width:860px;margin:0 auto;padding:20px;color:#222;background:#fdfcf9}
a{color:#2a5d8f}h1{font-size:28px;margin:0 0 6px}h2{font-size:19px;border-bottom:1px solid #ccc;margin-top:26px}
nav{margin-bottom:18px;font-size:14px}table{border-collapse:collapse;width:100%}td,th{padding:4px 8px;border-bottom:1px solid #eee;text-align:left;vertical-align:top}
.life{color:#666}.photo{float:right;max-width:200px;margin:0 0 10px 16px;border:1px solid #ccc}.letters a{margin-right:6px}
ol.notes{font-size:13px;color:#444}footer{margin-top:40px;font-size:12px;color:#777;border-top:1px solid #ddd;padding-top:8px}"""


def generate(con, out_dir, people, options=None):
    o = {'title': 'Our Family History', 'privatizeLiving': True, 'includeNotes': True, 'includeSources': True, 'includePhotos': True}
    o.update(options or {})
    s = m.settings(con)
    fmt = s.get('dateFormat', 'dmy')
    os.makedirs(os.path.join(out_dir, 'p'), exist_ok=True)
    os.makedirs(os.path.join(out_dir, 'media'), exist_ok=True)
    open(os.path.join(out_dir, 'style.css'), 'w').write(CSS)
    include = set(people)
    living = {r['PersonID'] for r in rows(con, 'SELECT PersonID FROM PersonTable WHERE Living=1')} if o['privatizeLiving'] else set()
    private = {r['PersonID'] for r in rows(con, 'SELECT PersonID FROM PersonTable WHERE IsPrivate=1')}
    include -= private

    def name(pid):
        if pid in living:
            return 'Living ' + E(m.primary_name(con, pid).get('Surname', ''))
        return E(m.person_name(con, pid))

    def link(pid, prefix=''):
        if not pid:
            return ''
        if pid not in include:
            return name(pid)
        return f'<a href="{prefix}{pid}.html">{name(pid)}</a>'

    def life(pid):
        if pid in living:
            return ''
        b, d = m.first_event(con, pid, (1, 3, 7)), m.first_event(con, pid, (2, 4))
        by, dy = (rmdate.year(b['Date']) if b else 0), (rmdate.year(d['Date']) if d else 0)
        return f'<span class="life">({by or "?"}–{dy or ""})</span>' if by or dy else ''

    def page(title, body, prefix=''):
        return (f'<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
                f'<title>{E(title)}</title><link rel="stylesheet" href="{prefix}style.css"></head><body>'
                f'<nav><a href="{prefix}index.html">Home</a> · <a href="{prefix}surnames.html">Surnames</a></nav>{body}'
                f'<footer>{E(o["title"])} — generated by Dzinde</footer></body></html>')

    for pid in include:
        out = [f'<h1>{name(pid)} {life(pid)}</h1>']
        if pid not in living:
            if o['includePhotos']:
                ph = m.primary_photo(con, pid)
                if ph and os.path.isfile(m.media_path(ph)):
                    fn = f"{ph['MediaID']}{os.path.splitext(ph['MediaFile'])[1].lower()}"
                    shutil.copy2(m.media_path(ph), os.path.join(out_dir, 'media', fn))
                    out.append(f'<img class="photo" src="../media/{fn}" alt="">')
            notes, refs = [], {}
            out.append('<table>')
            for f in m.facts_for(con, 'person', pid, s, include_shared=False):
                if f['private']:
                    continue
                sup = ''
                if o['includeSources']:
                    for c in m.citations_for(con, 2, f['id']):
                        if c['CitationID'] not in refs:
                            notes.append(c['footnote'])
                            refs[c['CitationID']] = len(notes)
                        sup += f'<sup>{refs[c["CitationID"]]}</sup>'
                place = ', '.join(x for x in (f['placeDetails'], f['place']) if x)
                out.append(f'<tr><th>{E(f["typeName"])}</th><td>{E(f["date"])}</td><td>{E(place)}'
                           f'{" — " + E(f["description"]) if f["description"] else ""}{sup}</td></tr>')
            out.append('</table>')
        fa, mo, _ = m.primary_parents(con, pid)
        if fa or mo:
            out.append(f'<h2>Parents</h2><p>{link(fa)} {life(fa)}<br>{link(mo)} {life(mo)}</p>')
        for f in m.spouse_families(con, pid):
            out.append(f'<h2>Family with {link(f["spouse"]) or "unknown spouse"} {life(f["spouse"])}</h2>')
            mar = m.first_event(con, f['FamilyID'], (300,), owner=1)
            if mar and pid not in living and f['spouse'] not in living:
                out.append(f'<p>Married {E(rmdate.format(mar["Date"], fmt))} {E(m.place_name(con, mar["PlaceID"]))}</p>')
            kids = m.children_of(con, f['FamilyID'])
            if kids:
                out.append('<ol>' + ''.join(f'<li>{link(c)} {life(c)}</li>' for c in kids) + '</ol>')
        if pid not in living:
            note = (rows(con, 'SELECT Note FROM PersonTable WHERE PersonID=?', pid) or [{}])[0].get('Note')
            if o['includeNotes'] and note:
                out.append(f'<h2>Notes</h2><p>{m.note_to_html(note)}</p>')
            if o['includeSources'] and notes:
                out.append('<h2>Sources</h2><ol class="notes">' + ''.join(f'<li>{n}</li>' for n in notes) + '</ol>')
        open(os.path.join(out_dir, 'p', f'{pid}.html'), 'w', encoding='utf-8').write(page(m.strip_tags(name(pid)), ''.join(out), '../'))

    by_surname = {}
    for pid in include:
        by_surname.setdefault(m.primary_name(con, pid).get('Surname') or '(unknown)', []).append(pid)
    letters = sorted({s_[0].upper() for s_ in by_surname if s_})
    idx = [f'<h1>Surnames</h1><p class="letters">' + ''.join(f'<a href="#{L}">{L}</a>' for L in letters) + '</p>']
    cur = None
    for sur in sorted(by_surname, key=str.lower):
        if sur[:1].upper() != cur:
            cur = sur[:1].upper()
            idx.append(f'<h2 id="{E(cur)}">{E(cur)}</h2>')
        ppl = sorted(by_surname[sur], key=lambda p: m.primary_name(con, p).get('Given') or '')
        idx.append(f'<h3>{E(sur)}</h3><ul>' + ''.join(f'<li>{link(p, "p/")} {life(p)}</li>' for p in ppl) + '</ul>')
    open(os.path.join(out_dir, 'surnames.html'), 'w', encoding='utf-8').write(page('Surnames', ''.join(idx)))
    prep = s.get('preparer') or {}
    home = (f'<h1>{E(o["title"])}</h1><p>{len(include)} people, {len(by_surname)} surnames.</p>'
            f'<p><a href="surnames.html">Browse the surname index →</a></p>' +
            (f'<p>Compiled by {E(prep.get("name"))}{" — " + E(prep.get("email")) if prep.get("email") else ""}</p>' if prep.get('name') else ''))
    open(os.path.join(out_dir, 'index.html'), 'w', encoding='utf-8').write(page(o['title'], home))
    return out_dir
